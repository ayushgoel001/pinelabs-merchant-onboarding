def test_upload_boundary_and_failures(browser, stack, monkeypatch):
    payload = scenario("happy")
    case = started(browser, stack, payload)
    good = document(payload, "bank")
    path = stack.path
    assert upload(browser, stack, case, "bank", b"not an image", ctype="image/png").status_code == 422
    assert upload(browser, stack, case, "bank", good, ctype="text/plain").status_code == 415
    assert upload(browser, stack, case, "bank", b"\x89PNG" + b"0" * (2 * 1024 * 1024 + 1)).status_code == 413
    bomb = io.BytesIO()
    Image.new("L", (3000, 3000), 255).save(bomb, "PNG")  # about 9 megapixels, but a tiny file
    big = upload(browser, stack, case, "bank", bomb.getvalue())
    assert big.status_code == 422 and "4 megapixels" in big.json()["detail"]
    assert upload(browser, stack, case, "bank", good, rev=99).status_code == 409  # stale revision
    assert upload(browser, stack, case, "bank", good, ctype="image/png",
                  query_string="").status_code == 200  # a good upload still works after every rejection
    rev = revision(stack, case)
    assert query(path, "SELECT count(*) AS n FROM extractions")[0]["n"] == 1
    other = Browser(stack.app)
    try:
        assert upload(other, stack, case, "bank", good, rev=rev).status_code == 403  # another browser has no access
        assert other.request("GET", f"/cases/{case}/documents/bank/image").status_code == 403
        assert upload(browser, stack, case, "bank", good, rev=rev).status_code == 200
        foreign = browser.request("POST", f"/api/cases/{case}/documents/bank?revision={revision(stack, case)}", content=good,
                                  headers={"Content-Type": "image/png", "Origin": "https://example.invalid"})
        assert foreign.status_code == 403
    finally:
        other.close()
    monkeypatch.setattr(ocr, "tesseract_command", lambda: None)
    count = len(query(path, "SELECT seq FROM events"))
    unavailable = upload(browser, stack, case, "bank", good)
    assert unavailable.status_code == 503 and unavailable.json()["detail"] == "OCR unavailable: structured evidence required"
    assert len(query(path, "SELECT seq FROM events")) == count  # nothing changed, nothing crashed
    stack.run_to(12)
    assert state(path, case) == "ACTIVE"
    assert upload(browser, stack, case, "bank", good).status_code == 409  # approved: servicing required


