def test_stored_extractions_are_immutable_and_the_gate_rechecks_them(browser, stack):
    from app import approval
    payload = scenario("happy")
    case = started(browser, stack, payload)
    upload(browser, stack, case, "bank", document(payload, "bank"))
    ex = extraction(stack, case, "bank")
    with db.write_tx(stack.path) as conn:
        for sql in ("UPDATE extractions SET min_confidence=100", "DELETE FROM extractions",
                    "UPDATE files SET data=x'00'", "DELETE FROM files",
                    "INSERT OR REPLACE INTO extractions(id,case_id,kind,revision,source_type,original_digest,render_digest,"
                    "engine,threshold,min_confidence,fields,created) "
                    f"SELECT id,case_id,kind,revision,source_type,original_digest,render_digest,engine,threshold,100,fields,created "
                    "FROM extractions"):
            with pytest.raises(sqlite3.IntegrityError, match="immutable"):
                conn.execute(sql)
        # verify_integrity refuses an extraction whose values differ from the saved document or whose image changed.
        row = conn.execute("SELECT * FROM extractions").fetchone()
        record = dict(row, fields=json.loads(row["fields"]))
        assert evidence.verify_integrity(conn, {"bank": record}, {"bank": payload["documents"]["bank"]})
        assert not evidence.verify_integrity(conn, {"bank": record}, {"bank": dict(payload["documents"]["bank"], account="SYNACCT-0099")})
        assert not evidence.verify_integrity(conn, {"bank": dict(record, render_digest="0" * 64)}, {"bank": payload["documents"]["bank"]})
    # An unreadable document with every issue force-resolved in SQL still cannot produce a receipt.
    upload(browser, stack, case, "tax", document(payload, "tax", blur=4.0))
    with db.write_tx(stack.path) as conn:
        conn.execute("SAVEPOINT force")
        conn.execute("UPDATE review_items SET status='RESOLVED' WHERE case_id=?", (case,))
        assert approval.build_receipt(conn, conn.execute("SELECT * FROM applications WHERE id=?", (case,)).fetchone()) is None
        conn.execute("ROLLBACK TO force")
        conn.execute("RELEASE force")


