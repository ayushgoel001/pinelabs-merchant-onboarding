def test_d01_uploaded_tax_png_is_read_validated_and_drives_approval(browser, stack):
    payload = scenario("missing-tax")
    case = browser.create(payload)
    assert state(stack.path, case) == "NEEDS_INFO"
    stack.sync()
    response = upload(browser, stack, case, "tax", document(payload, "tax"))
    assert response.status_code == 200, response.text
    ex = extraction(stack, case, "tax")
    assert ex["source_type"] == "png" and ex["engine"].startswith("tesseract")
    values = {label: f["value"] for label, f in ex["fields"].items()}
    assert values == {"name": "ACME TRADERS PVT LTD".replace("ACME TRADERS", "ASTER MEADOW STORES"),
                      "pan": "SYNPAN-0002", "gst": "SYNGST-29-SYNPAN-0002-1"}
    assert all(f["confidence"] is not None and f["confidence"] >= ex["threshold"] for f in ex["fields"].values())
    assert state(stack.path, case) == "VERIFYING" and active(stack.path, case) == []
    # The page shows the extracted fields, validation status and a real confidence for each OCR field.
    page = browser.request("GET", "/cases/" + case).text
    assert "Uploaded documents" in page and f"/cases/{case}/documents/tax/image" in page
    assert page.count("OCR confidence") >= 3 and "OCR text" in page
    stack.tick()
    stack.run_to(12)
    assert state(stack.path, case) == "ACTIVE" and counts(stack, case) == (1, 1, 1)
    # The sealed receipt names the extraction, its engine, confidences and the digest of the image that was read.
    receipt = sealed(stack, case)["evidence"]["extractions"]["tax"]
    assert receipt["render_digest"] == ex["render_digest"] and receipt["min_confidence"] == ex["min_confidence"]
    served = browser.request("GET", f"/cases/{case}/documents/tax/image")
    assert served.status_code == 200 and served.content[:8] == b"\x89PNG\r\n\x1a\n"
    assert hashlib.sha256(served.content).hexdigest() == ex["render_digest"]
    assert "EVIDENCE_UPDATED" in [e["event"] for e in query(stack.path, "SELECT event FROM events WHERE case_id=?", case)]


