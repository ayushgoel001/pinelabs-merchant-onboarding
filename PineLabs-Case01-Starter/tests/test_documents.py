    assert rows == [{"subject_revision": 2, "action": "ACCEPT_EXTRACTION", "actor": "operator"}] * 2  # document revision
    stack.tick()
    assert state(stack.path, case) == "ACTIVE" and counts(stack, case) == (1, 1, 1)
    bound = sealed(stack, case)["evidence"]["extractions"]["identity"]
    assert bound["low_confidence_accepted"] == ["name", "pan"] and bound["threshold"] == 99.0


