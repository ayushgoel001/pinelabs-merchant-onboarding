def test_pdf_with_a_text_layer_is_rendered_and_read(browser, stack):
    payload = scenario("happy")
    case = started(browser, stack, payload)
    lines = ["Beneficiary: Acme Traders Private Limited", "Account: SYNACCT-0001", "Routing: SYNIFSC-0001"]
    commands = "BT /F1 26 Tf 40 700 Td 34 TL " + " ".join(f"({line}) Tj T*" for line in lines) + " ET"
    objects = ["<< /Type /Catalog /Pages 2 0 R >>", "<< /Type /Pages /Kids [3 0 R] /Count 1 >>",
               "<< /Type /Page /Parent 2 0 R /MediaBox [0 0 612 792] /Contents 4 0 R "
               "/Resources << /Font << /F1 5 0 R >> >> >>",
               f"<< /Length {len(commands)} >>\nstream\n{commands}\nendstream", "<< /Type /Font /Subtype /Type1 /BaseFont /Helvetica >>"]
    pdf, offsets = b"%PDF-1.4\n", []
    for number, body in enumerate(objects, 1):
        offsets.append(len(pdf))
        pdf += f"{number} 0 obj\n{body}\nendobj\n".encode()
    xref = len(pdf)
    pdf += f"xref\n0 {len(objects) + 1}\n0000000000 65535 f \n".encode()
    pdf += "".join(f"{o:010d} 00000 n \n" for o in offsets).encode()
    pdf += f"trailer\n<< /Size {len(objects) + 1} /Root 1 0 R >>\nstartxref\n{xref}\n%%EOF".encode()
    assert upload(browser, stack, case, "bank", pdf, "pdf").status_code == 200
    ex = extraction(stack, case, "bank")
    assert ex["source_type"] == "pdf" and {k: f["value"] for k, f in ex["fields"].items()} == payload["documents"]["bank"]


# ---------------------------------------------------------------- missing, blurred, unreadable and conflicting evidence

def test_blurred_document_goes_to_operator_and_cannot_be_accepted_or_approved(browser, stack):
    payload = scenario("happy")
    case = started(browser, stack, payload)
    assert upload(browser, stack, case, "tax", document(payload, "tax", blur=4.0)).status_code == 200
    ex = extraction(stack, case, "tax")
    assert all(f["value"] is None for f in ex["fields"].values())  # nothing readable, nothing retained
    assert ex["min_confidence"] == 0.0  # an unread field counts as zero in the document-level figure
    unreadable = [i for i in active(stack.path, case) if i["cause"] == "EVIDENCE_UNREADABLE"]
    assert {i["subject"] for i in unreadable} == {"tax.name", "tax.pan", "tax.gst"}
    assert all(i["owner"] == "OPERATOR" for i in unreadable) and state(stack.path, case) == "IN_REVIEW"
    stack.run_to(12)  # earlier provider results settle, but nothing can approve
    assert counts(stack, case) == (0, 0, 0) and state(stack.path, case) == "IN_REVIEW"
    login(browser, stack.path)
    page = browser.request("GET", "/cases/" + case).text
    assert "Request correction" in page and "Accept low-confidence value" not in page
    first = issue(stack, case, "EVIDENCE_UNREADABLE")
    assert decide(browser, case, first, "ACCEPT_EXTRACTION").status_code == 409  # nothing was read to accept
    assert decide(browser, case, first, "REQUEST_CORRECTION").status_code == 200
    assert query(stack.path, "SELECT action,actor,reason FROM decisions WHERE issue_id=?", first["id"]) == [
        {"action": "REQUEST_CORRECTION", "actor": "operator", "reason": REASONS["REQUEST_CORRECTION"][0]}]
    assert "operator" in [e["actor"] for e in query(stack.path, "SELECT actor FROM events WHERE case_id=?", case)]
    # The merchant replaces it with a clear scan. The new revision is read, the issues clear and the case approves.
    assert upload(browser, stack, case, "tax", document(payload, "tax")).status_code == 200
    assert not [i for i in active(stack.path, case) if i["cause"] == "EVIDENCE_UNREADABLE"]
    stack.tick()
    stack.run_to(30)
    assert state(stack.path, case) == "ACTIVE" and counts(stack, case) == (1, 1, 1)
    assert extraction(stack, case, "tax")["revision"] == 3


def test_noisy_scan_is_never_approved(browser, stack):
    """A scan degraded with random speckle: whatever the engine manages to read, nothing unreadable can approve."""
    import random
    payload = scenario("happy")
    case = started(browser, stack, payload)
    image = samples.render("bank", payload["documents"]["bank"])
    rnd, px = random.Random(7), image.load()
    for _ in range(int(image.width * image.height * 0.02)):
        v = rnd.choice((0, 255))
        px[rnd.randrange(image.width), rnd.randrange(image.height)] = (v, v, v)
    assert upload(browser, stack, case, "bank", samples.encode(image, "png")).status_code == 200
    causes = {i["cause"] for i in active(stack.path, case)}
    assert causes & {"EVIDENCE_UNREADABLE", "EVIDENCE_CONFLICT"} and state(stack.path, case) == "IN_REVIEW"
    stack.run_to(12)
    assert counts(stack, case) == (0, 0, 0)


