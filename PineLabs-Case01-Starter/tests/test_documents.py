def test_gate_refuses_tampered_ocr_evidence_even_when_the_values_still_agree(browser, stack):
    """verify_integrity inside the gate: the image the OCR engine read must still hash to its recorded digest."""
    from app import approval
    payload = scenario("happy")
    case = started(browser, stack, payload)
    assert upload(browser, stack, case, "bank", document(payload, "bank")).status_code == 200
    stack.run_to(12)
    assert state(stack.path, case) == "ACTIVE"
    with db.write_tx(stack.path) as conn:
        row = conn.execute("SELECT * FROM applications WHERE id=?", (case,)).fetchone()
        assert approval.build_receipt(conn, row) is not None  # untouched evidence still qualifies
        conn.execute("SAVEPOINT tamper")
        conn.execute("DROP TRIGGER immutable_files_UPDATE")  # what a hostile database edit would have to do first
        conn.execute("UPDATE files SET data=x'00'")
        assert approval.build_receipt(conn, row) is None
        conn.execute("ROLLBACK TO tamper")
        conn.execute("SAVEPOINT tamper2")
        conn.execute("DROP TRIGGER immutable_extractions_UPDATE")
        conn.execute("""UPDATE extractions SET fields=replace(fields,'"confidence":9','"confidence":1') WHERE kind='bank'""")
        conn.execute("UPDATE extractions SET fields=replace(fields,'SYNACCT-0001','SYNACCT-0099') WHERE kind='bank'")
        assert approval.build_receipt(conn, row) is None  # values no longer equal the saved document
        conn.execute("ROLLBACK TO tamper2")
