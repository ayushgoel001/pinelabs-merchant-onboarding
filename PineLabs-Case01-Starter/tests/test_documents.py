    payload = scenario("happy")
    case = started(browser, stack, payload)
    assert upload(browser, stack, case, "identity", document(payload, "identity")).status_code == 200
    ex = extraction(stack, case, "identity")
    assert ex["threshold"] == 99.0 and 0 < ex["min_confidence"] < 99
    low = [i for i in active(stack.path, case) if i["cause"] == "EVIDENCE_UNREADABLE"]
    assert {i["subject"] for i in low} == {"identity.name", "identity.pan"}
    assert state(stack.path, case) == "IN_REVIEW"
    stack.run_to(12)
    assert counts(stack, case) == (0, 0, 0)
    login(browser, stack.path)
    page = browser.request("GET", "/cases/" + case).text
    assert page.count("Accept low-confidence value") >= 2
    first, second = low
    assert decide(browser, case, first, "ACCEPT_EXTRACTION", reason="not a listed reason").status_code == 422
    assert decide(browser, case, first, "ACCEPT_EXTRACTION", version=first["version"] + 1).status_code == 409
    assert decide(browser, case, first, "ACCEPT_EXTRACTION").status_code == 200
    assert decide(browser, case, first, "ACCEPT_EXTRACTION").status_code == 409  # already decided
    assert counts(stack, case) == (0, 0, 0) and state(stack.path, case) == "IN_REVIEW"
    assert decide(browser, case, second, "ACCEPT_EXTRACTION").status_code == 200
