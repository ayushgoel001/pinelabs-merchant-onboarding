TYPES = {"png": "image/png", "jpeg": "image/jpeg", "pdf": "application/pdf"}


def revision(stack, case):
    return query(stack.path, "SELECT data_revision FROM applications WHERE id=?", case)[0]["data_revision"]


def upload(browser, stack, case, kind, data, fmt="png", rev=None, ctype=None, query_string=""):
    rev = revision(stack, case) if rev is None else rev
    return browser.request("POST", f"/api/cases/{case}/documents/{kind}?revision={rev}{query_string}", content=data,
                           headers={"Content-Type": ctype or TYPES[fmt]})


def document(payload, kind, fmt="png", blur=0.0, **override):
    fields = dict(payload["documents"].get(kind) or {})
    if kind not in payload["documents"]:
        from app.fixtures import documents
        fields = documents(payload["merchant"])[kind]
    fields.update(override)
    return samples.make_document(kind, fields, fmt, blur)


def extraction(stack, case, kind):
    rows = query(stack.path, """SELECT e.* FROM extractions e WHERE e.case_id=? AND e.kind=?
                             ORDER BY revision DESC""", case, kind)
    return dict(rows[0], fields=json.loads(rows[0]["fields"])) if rows else None


def finding(browser, stack, case, doc, label):
    from app.web import case_view
    return next(f for f in case_view(stack.path, case)["fields"] if f["document"] == doc and f["label"] == label)


def sealed(stack, case):
    rows = query(stack.path, "SELECT receipt FROM approvals WHERE case_id=?", case)
    return json.loads(rows[0]["receipt"]) if rows else None


